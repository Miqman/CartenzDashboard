export function toArticleSlug(value: string): string {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-");
}

export function getArticleByJudul(judul: string): ArticleItem | undefined {
  return articleData.find((a) => a.judul === judul);
}

export function getArticleByLocalSlug(slug: string): ArticleItem | undefined {
  return articleData.find((a) => toArticleSlug(a.judul) === slug);
}

export function getRelatedArticles(
  currentJudul: string,
  limit = 3,
): ArticleItem[] {
  return articleData.filter((a) => a.judul !== currentJudul).slice(0, limit);
}
